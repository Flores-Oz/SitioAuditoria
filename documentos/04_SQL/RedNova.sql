-- SQL-07 | Alertas críticas pendientes de cierre | E-07 | R-XX/T-XX por coordinar
-- LIMITACION: Que falte cierre documental no demuestra que nadie haya respondido.
SELECT AlertaId, FechaHora, Severidad, Estado, FechaCierre
FROM dbo.Alertas WHERE Severidad = N'CRITICA' AND FechaCierre IS NULL
ORDER BY FechaHora;
GO

-- SQL-08 | Respaldos sin restauración reciente o verificación | E-08 | R-XX/T-XX por coordinar
-- LIMITACION: Umbral de 90 días: criterio de laboratorio a validar contra política y BIA del cliente.
SELECT Sistema, MAX(FechaBackup) AS UltimoBackup,
       MIN(CAST(IntegridadVerificada AS INT)) AS IntegridadMinima,
       MIN(CAST(RestauracionProbada AS INT)) AS RestauracionMinima,
       MAX(FechaUltimaRestauracion) AS UltimaRestauracion
FROM dbo.Backups
GROUP BY Sistema
HAVING MIN(CAST(IntegridadVerificada AS INT)) = 0
    OR MIN(CAST(RestauracionProbada AS INT)) = 0
    OR MAX(FechaUltimaRestauracion) IS NULL
    OR DATEDIFF(DAY, MAX(FechaUltimaRestauracion), '2026-10-14T00:00:00') > 90
ORDER BY Sistema;
GO

-- SQL-09 | Transferencias sin clasificación de contenido | E-04 | R-XX/T-XX por coordinar
-- LIMITACION: El volumen no demuestra fuga. Se requieren destino, contenido, proceso originador y contexto de red.
SELECT TransferenciaId, FechaHora, BytesTransferidos, Destino,
       ClasificacionContenido, EstadoAutorizacion, SesionId
FROM dbo.Transferencias
WHERE ClasificacionContenido IS NULL OR EstadoAutorizacion = N'NO_VERIFICADA'
ORDER BY FechaHora;
GO

-- SQL-10 | Órdenes con identificador comercial duplicado | E-05 | R-XX/T-XX por coordinar
-- LIMITACION: Dos órdenes sintéticas comparten un código; no es un duplicado acreditado del caso.
SELECT Codigo, COUNT(*) AS Duplicados
FROM dbo.Ordenes GROUP BY Codigo HAVING COUNT(*) > 1
ORDER BY Codigo;
GO

-- SQL-11 | Sesiones fuera del horario operativo de ejemplo | E-02 | R-XX/T-XX por coordinar
-- LIMITACION: El tramo 06:00 a 21:59 es ficticio; un acceso nocturno no demuestra irregularidad sin política de horarios.
SELECT u.Codigo AS Usuario, s.FechaInicio, s.TipoAcceso
FROM dbo.Sesiones AS s JOIN dbo.Usuarios AS u ON u.UsuarioId = s.UsuarioId
WHERE DATEPART(HOUR, s.FechaInicio) < 6 OR DATEPART(HOUR, s.FechaInicio) >= 22
ORDER BY s.FechaInicio;
GO

-- SQL-12 | Intervalo anómalo entre respaldos del mismo sistema | E-08 | R-XX/T-XX por coordinar
-- LIMITACION: Intervalo >24h es un umbral de laboratorio; comprobar frecuencias aprobadas por sistema.
WITH Ordenados AS (
  SELECT Sistema, FechaBackup,
         LAG(FechaBackup) OVER (PARTITION BY Sistema ORDER BY FechaBackup) AS BackupAnterior
  FROM dbo.Backups
)
SELECT Sistema, BackupAnterior, FechaBackup,
       DATEDIFF(HOUR, BackupAnterior, FechaBackup) AS HorasEntreBackups
FROM Ordenados
WHERE BackupAnterior IS NOT NULL AND DATEDIFF(HOUR, BackupAnterior, FechaBackup) > 24
ORDER BY Sistema;
GO

