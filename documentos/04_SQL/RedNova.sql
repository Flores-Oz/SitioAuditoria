GO

-- SQL-05 | Concentración de cambios de órdenes | E-05 | R-XX/T-XX por coordinar
-- LIMITACION: 216 cambios se representan como simulación. No consta usuario responsable ni autorización.
SELECT CONVERT(VARCHAR(16), h.FechaHora, 120) AS Minuto,
       COUNT(*) AS TotalCambios, COUNT(DISTINCT h.OrdenId) AS OrdenesDistintas
FROM dbo.HistorialOrdenes AS h
GROUP BY CONVERT(VARCHAR(16), h.FechaHora, 120)
HAVING COUNT(*) >= 50 ORDER BY Minuto;
GO

