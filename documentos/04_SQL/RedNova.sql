CREATE TABLE dbo.Usuarios (
    [UsuarioId] INT NOT NULL PRIMARY KEY,
    [Codigo] NVARCHAR(50) NOT NULL UNIQUE,
    [Nombre] NVARCHAR(150) NOT NULL,
    [Tipo] NVARCHAR(150) NOT NULL,
    [EstadoLaboral] NVARCHAR(150) NOT NULL,
    [FechaBaja] DATE NULL,
    [Activo] BIT NOT NULL,
    [Privilegiado] BIT NOT NULL,
    [CuentaCompartida] BIT NOT NULL,
    [UltimaRecertificacion] DATE NULL
);
GO

CREATE TABLE dbo.Privilegios (
    [PrivilegioId] INT NOT NULL PRIMARY KEY,
    [UsuarioId] INT NOT NULL,
    [Recurso] NVARCHAR(150) NOT NULL,
    [Nivel] NVARCHAR(150) NOT NULL,
    [Vigente] BIT NOT NULL,
    [FechaOtorgamiento] DATE NOT NULL,
    CONSTRAINT FK_Privilegios_UsuarioId FOREIGN KEY ([UsuarioId]) REFERENCES dbo.Usuarios([UsuarioId])
);
GO

CREATE TABLE dbo.Sesiones (
    [SesionId] INT NOT NULL PRIMARY KEY,
    [UsuarioId] INT NOT NULL,
    [FechaInicio] DATETIME2(0) NOT NULL,
    [FechaFin] DATETIME2(0) NULL,
    [TipoAcceso] NVARCHAR(150) NOT NULL,
    [IpOrigen] NVARCHAR(150) NULL,
    [MfaUsado] BIT NULL,
    [Resultado] NVARCHAR(150) NOT NULL,
    CONSTRAINT FK_Sesiones_UsuarioId FOREIGN KEY ([UsuarioId]) REFERENCES dbo.Usuarios([UsuarioId])
);
GO

CREATE TABLE dbo.EventosPrivilegios (
    [EventoId] INT NOT NULL PRIMARY KEY,
    [FechaHora] DATETIME2(0) NOT NULL,
    [UsuarioId] INT NULL,
    [SesionId] INT NULL,
    [Accion] NVARCHAR(150) NOT NULL,
    [EstadoAtribucion] NVARCHAR(150) NOT NULL,
    CONSTRAINT FK_EventosPrivilegios_UsuarioId FOREIGN KEY ([UsuarioId]) REFERENCES dbo.Usuarios([UsuarioId]),
    CONSTRAINT FK_EventosPrivilegios_SesionId FOREIGN KEY ([SesionId]) REFERENCES dbo.Sesiones([SesionId])
);
GO

CREATE TABLE dbo.BitacoraConsultas (
    [LecturaId] INT NOT NULL PRIMARY KEY,
    [FechaHora] DATETIME2(0) NOT NULL,
    [UsuarioId] INT NULL,
    [SesionId] INT NULL,
    [Objeto] NVARCHAR(150) NOT NULL,
    [FilasLeidas] INT NOT NULL,
    [Origen] NVARCHAR(150) NOT NULL,
    CONSTRAINT FK_BitacoraConsultas_UsuarioId FOREIGN KEY ([UsuarioId]) REFERENCES dbo.Usuarios([UsuarioId]),
    CONSTRAINT FK_BitacoraConsultas_SesionId FOREIGN KEY ([SesionId]) REFERENCES dbo.Sesiones([SesionId])
);
GO

CREATE TABLE dbo.Transferencias (
    [TransferenciaId] INT NOT NULL PRIMARY KEY,
    [FechaHora] DATETIME2(0) NOT NULL,
    [SesionId] INT NULL,
    [BytesTransferidos] BIGINT NOT NULL,
    [Destino] NVARCHAR(150) NOT NULL,
    [ClasificacionContenido] NVARCHAR(150) NULL,
    [EstadoAutorizacion] NVARCHAR(150) NOT NULL,
    CONSTRAINT FK_Transferencias_SesionId FOREIGN KEY ([SesionId]) REFERENCES dbo.Sesiones([SesionId])
);
GO

CREATE TABLE dbo.Ordenes (
    [OrdenId] INT NOT NULL PRIMARY KEY,
    [Codigo] NVARCHAR(150) NOT NULL,
    [FechaCreacion] DATETIME2(0) NOT NULL,
    [MontoQ] DECIMAL(12,2) NOT NULL,
    [Estado] NVARCHAR(150) NOT NULL
);
GO

CREATE TABLE dbo.HistorialOrdenes (
    [HistorialId] INT NOT NULL PRIMARY KEY,
    [OrdenId] INT NOT NULL,
    [FechaHora] DATETIME2(0) NOT NULL,
    [UsuarioId] INT NULL,
    [Campo] NVARCHAR(150) NOT NULL,
    [ValorAnterior] NVARCHAR(150) NOT NULL,
    [ValorNuevo] NVARCHAR(150) NOT NULL,
    [Ticket] NVARCHAR(150) NULL,
    CONSTRAINT FK_HistorialOrdenes_OrdenId FOREIGN KEY ([OrdenId]) REFERENCES dbo.Ordenes([OrdenId]),
    CONSTRAINT FK_HistorialOrdenes_UsuarioId FOREIGN KEY ([UsuarioId]) REFERENCES dbo.Usuarios([UsuarioId])
);
GO

CREATE TABLE dbo.CambiosSistema (
    [CambioId] INT NOT NULL PRIMARY KEY,
    [FechaHora] DATETIME2(0) NOT NULL,
    [Sistema] NVARCHAR(150) NOT NULL,
    [Version] NVARCHAR(150) NOT NULL,
    [Ticket] NVARCHAR(150) NULL,
    [AprobacionFormal] BIT NULL,
    [Aprobador] NVARCHAR(150) NULL
