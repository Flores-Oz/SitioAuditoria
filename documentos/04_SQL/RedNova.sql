GO

CREATE TABLE dbo.Backups (
    [BackupId] INT NOT NULL PRIMARY KEY,
    [FechaBackup] DATETIME2(0) NOT NULL,
    [Sistema] NVARCHAR(150) NOT NULL,
    [Tipo] NVARCHAR(150) NOT NULL,
    [Completo] BIT NOT NULL,
    [IntegridadVerificada] BIT NOT NULL,
    [RestauracionProbada] BIT NOT NULL,
    [FechaUltimaRestauracion] DATETIME2(0) NULL
