-- PRUEBAS DE AUDITORIA: SOLO SELECT. SQL-01 a SQL-12
-- R-XX y T-XX deben reemplazarse con codigos del Integrante 1.
-- ============================================================

-- SQL-01 | Cuentas con baja laboral que siguen activas | E-01 | R-XX/T-XX por coordinar
-- LIMITACION: Una fila simulada evidencia una cuenta activa tras baja; no acredita un caso real.
SELECT u.Codigo AS Usuario, u.FechaBaja, u.Activo
FROM dbo.Usuarios AS u
WHERE u.FechaBaja IS NOT NULL AND u.Activo = 1
ORDER BY u.Codigo;
GO

-- SQL-02 | Cuentas administrativas compartidas | E-01 | R-XX/T-XX por coordinar
-- LIMITACION: Cuenta compartida ficticia; requiere registros de atribución individual.
SELECT u.Codigo AS Usuario, p.Recurso, p.Nivel
FROM dbo.Usuarios AS u
JOIN dbo.Privilegios AS p ON p.UsuarioId = u.UsuarioId
WHERE u.CuentaCompartida = 1 AND p.Vigente = 1
ORDER BY u.Codigo;
GO

-- SQL-03 | Sesiones remotas exitosas sin MFA | E-02 | R-XX/T-XX por coordinar
-- LIMITACION: Muestra la sesión sin MFA; no demuestra por sí sola que esa cuenta causara el ataque.
SELECT u.Codigo AS Usuario, s.FechaInicio, s.TipoAcceso, s.MfaUsado, s.IpOrigen
FROM dbo.Sesiones AS s JOIN dbo.Usuarios AS u ON u.UsuarioId = s.UsuarioId
WHERE s.TipoAcceso = N'VPN' AND s.Resultado = N'EXITOSO'
  AND s.MfaUsado = 0
ORDER BY s.FechaInicio;
GO

-- SQL-04 | Lecturas masivas registradas | E-03 | R-XX/T-XX por coordinar
-- LIMITACION: 31,840 filas es dato preliminar del caso representado en laboratorio; no hay atribución autenticada.
